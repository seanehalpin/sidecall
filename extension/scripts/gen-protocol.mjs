// Generate src/lib/protocol.gen.ts from ../protocol/sidecall.schema.json.
//
//   pnpm gen:protocol
//
// The daemon's Pydantic models are the source of truth (SPEC §9). The schema is
// lightly normalised before compiling, without changing any shapes:
// - property-level `title`s are dropped, otherwise json-schema-to-typescript
//   emits a named alias per property (`type Id = string`, `type Ts = number`, …)
//   that collide across messages;
// - the root container is renamed so it reads as what it is.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { compile } from 'json-schema-to-typescript';

const here = dirname(fileURLToPath(import.meta.url));
const schemaPath = resolve(here, '../../protocol/sidecall.schema.json');
const outPath = resolve(here, '../src/lib/protocol.gen.ts');

const schema = JSON.parse(await readFile(schemaPath, 'utf8'));

function stripPropertyTitles(node) {
  if (Array.isArray(node)) return node.forEach(stripPropertyTitles);
  if (!node || typeof node !== 'object') return;
  if (node.properties && typeof node.properties === 'object') {
    for (const prop of Object.values(node.properties)) {
      if (prop && typeof prop === 'object' && !('$ref' in prop)) delete prop.title;
    }
  }
  for (const value of Object.values(node)) stripPropertyTitles(value);
}
stripPropertyTitles(schema);
// The two unions are named via their own titles.
schema.properties.client.title = 'ClientMessage';
schema.properties.server.title = 'ServerMessage';
schema.title = 'SidecallProtocol';

const banner = `/* eslint-disable */
// DO NOT EDIT. Generated by \`pnpm gen:protocol\` from protocol/sidecall.schema.json,
// which is exported from the daemon's Pydantic models (daemon/src/sidecall/protocol/).
// Change the Python models, re-export the schema, then re-run the generator.`;

const ts = await compile(schema, 'SidecallProtocol', {
  bannerComment: banner,
  additionalProperties: false,
  unreachableDefinitions: true,
  strictIndexSignatures: true,
  style: { singleQuote: true },
});

await writeFile(outPath, ts);
console.log(`wrote ${outPath}`);
